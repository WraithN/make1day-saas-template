import type { Metadata } from "next";
import Link from "next/link";
import { notFound } from "next/navigation";
import { getLang, tr } from "@/lib/i18n-server";
import { TEMPLATES, getTemplate } from "@/lib/content/templates";
import { TemplateSite } from "@/components/TemplateSite";

export function generateStaticParams() {
  return TEMPLATES.map((t) => ({ slug: t.slug }));
}

export async function generateMetadata({
  params,
}: {
  params: Promise<{ slug: string }>;
}): Promise<Metadata> {
  const { slug } = await params;
  const tpl = getTemplate(slug);
  // The root layout's title template appends "· make1day" — don't add it here.
  if (!tpl) return { title: "Preview", robots: { index: false } };
  const name = tpl.name.en;
  return {
    title: `Preview: ${name}`,
    description: `Live preview of a site generated by the ${name} template.`,
    robots: { index: false },
  };
}

export default async function TemplatePreviewPage({
  params,
}: {
  params: Promise<{ slug: string }>;
}) {
  const { slug } = await params;
  const tpl = getTemplate(slug);
  if (!tpl) notFound();
  const lang = await getLang();

  return (
    <div className="min-h-screen bg-bg">
      <div className="sticky top-0 z-50 border-b border-line bg-bg/90 backdrop-blur">
        <div className="wrap flex items-center justify-between gap-3 py-3">
          <Link
            href="/templates"
            className="text-sm font-medium text-ink-soft hover:text-accent"
          >
            ← {tr(lang, "templates.backToGallery")}
          </Link>
          <Link href={`/builder?style=${tpl.styleId}`} className="btn-solid text-[14px]">
            {tr(lang, "templates.useInBuilder")}
          </Link>
        </div>
      </div>

      <TemplateSite tpl={tpl} lang={lang} />

      <p className="wrap py-6 text-center text-[13px] text-muted">
        {tr(lang, "templates.livePreviewNote")}
      </p>
    </div>
  );
}
