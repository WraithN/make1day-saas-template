// Clipboard helper that NEVER throws: async Clipboard API first (can reject
// with NotAllowedError when the document lacks focus/permission, or throw
// synchronously on older Safari), then a hidden-textarea execCommand fallback.
// Returns false when both fail so callers can reflect the state instead of
// surfacing an unhandled rejection (React dev overlay / console noise).

export async function copyText(text: string): Promise<boolean> {
  try {
    if (typeof navigator !== "undefined" && navigator.clipboard?.writeText) {
      await navigator.clipboard.writeText(text);
      return true;
    }
  } catch {
    /* fall through to the legacy path */
  }
  try {
    if (typeof document === "undefined") return false;
    const ta = document.createElement("textarea");
    ta.value = text;
    ta.setAttribute("readonly", "");
    ta.style.position = "fixed";
    ta.style.top = "-1000px";
    ta.style.opacity = "0";
    document.body.appendChild(ta);
    ta.select();
    const ok = document.execCommand("copy");
    document.body.removeChild(ta);
    return ok;
  } catch {
    return false;
  }
}
