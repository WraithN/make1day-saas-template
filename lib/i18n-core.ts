// Translate `{{g}}…{{/g}}` into a gradient-highlighted span (our brand accent).
export function applyMarkup(s: string): string {
  return s.replace(
    /\{\{g\}\}([\s\S]*?)\{\{\/g\}\}/g,
    '<span class="grad-text">$1</span>',
  );
}

/** HTML-escape a value before it is interpolated into translated markup. */
function escapeHtml(v: string): string {
  return v
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

/**
 * Replace `{name}` placeholders with runtime values. Used for copy that
 * depends on server-side state, e.g. "powered by {provider}".
 */
export function interpolate(
  s: string,
  vars?: Record<string, string | number>,
): string {
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (match, key: string) =>
    Object.prototype.hasOwnProperty.call(vars, key)
      ? escapeHtml(String(vars[key]))
      : match,
  );
}

