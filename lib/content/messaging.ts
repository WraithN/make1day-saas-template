const BY_LANG: Record<Lang, MessagingCopy> = { en, zh, ja, fr, de };

/** Complete copy for a language (never a partial fallback object). */
export function msgCopy(lang: Lang): MessagingCopy {
  return BY_LANG[lang] ?? en;
}

/** One translated string, with `{name}` placeholders HTML-escaped and filled. */
export function msg(
  lang: Lang,
  key: MsgKey,
  vars?: Record<string, string | number>,
): string {
  const base = BY_LANG[lang]?.[key] ?? en[key];
  return interpolate(base, vars);
}
